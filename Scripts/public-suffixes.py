#!/usr/bin/env python3
#
# Refreshes Sources/FirewallPolicy/PublicSuffixes.swift from the Public Suffix
# List (https://publicsuffix.org, MPL-2.0), which says where people register
# names: `co.uk`, `gov.lb`, `myshopify.com` (#318). `SiteName` reads it to
# tell a name's site.
#
# The rules are committed, not downloaded at build time, so a build never
# depends on the network and an old tag rebuilds the same. Refresh before a
# release now and then, in a pull request of its own.
#
# Usage: python3 -I Scripts/public-suffixes.py

import os
import sys
import urllib.request

URL = "https://publicsuffix.org/list/public_suffix_list.dat"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Sources", "FirewallPolicy",
                   "PublicSuffixes.swift")


def ascii_rule(rule):
    """A rule as macOS hands the filter names: each label in punycode."""
    prefix = ""
    if rule.startswith("!"):
        prefix, rule = "!", rule[1:]
    labels = []
    for label in rule.split("."):
        if label == "*" or label.isascii():
            labels.append(label.lower())
        else:
            labels.append("xn--" + label.lower().encode("punycode").decode("ascii"))
    return prefix + ".".join(labels)


def main():
    request = urllib.request.Request(URL, headers={"User-Agent": "NetworkMonitor-public-suffixes"})
    text = urllib.request.urlopen(request, timeout=60).read().decode("utf-8")
    version = next((line.split(":", 1)[1].strip() for line in text.splitlines() if line.startswith("// VERSION:")),
                   "unknown")
    rules = []
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("//"):
            continue
        rule = ascii_rule(line.split()[0])
        if rule not in rules:
            rules.append(rule)
    if len(rules) < 5000:
        sys.exit(f"only {len(rules)} rules from {URL}; refusing to write them")
    body = "\n".join("        " + rule for rule in rules)
    swift = f"""// Generated by Scripts/public-suffixes.py from the Public Suffix List
// ({URL}), version {version}.
// MPL-2.0: https://mozilla.org/MPL/2.0/. Don't edit; run the script again.

extension SiteName {{
    /// Every rule, one a line, its labels in punycode: a suffix, `*.` for
    /// every name one label under one, or `!` for a name that isn't one
    /// although a `*.` rule covers it.
    static let publicSuffixRules = \"\"\"
{body}
        \"\"\"
}}
"""
    with open(OUT, "w", encoding="utf-8") as file:
        file.write(swift)
    print(f"{len(rules)} rules, version {version}")


main()
